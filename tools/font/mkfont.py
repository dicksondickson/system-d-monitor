#!/usr/bin/env python3
"""Generate src/gfx/font_ter10x20.h from the Terminus 10x20 BDFs.

  tools/font/mkfont.py            # writes src/gfx/font_ter10x20.h

Each glyph is 20 rows of uint16, MSB = leftmost pixel (10 used bits), as in
the BDF. Codepoints are sorted so the firmware can binary-search them.
Terminus is SIL OFL 1.1: third_party/terminus/OFL.TXT.
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "third_party", "terminus")
OUT = os.path.join(ROOT, "src", "gfx", "font_ter10x20.h")

ASCII = list(range(0x20, 0x7F))
# Extra glyphs the UI uses (spec.md §6–7).
EXTRA = [
    0x00B7,                                  # ·
    0x2014, 0x2026,                          # — …
    0x2039, 0x203A,                          # ‹ ›
    0x2261, 0x25B6,                          # ≡ (settings) ▶ (selected)
    0x256D, 0x256E, 0x256F, 0x2570,          # ╭╮╯╰ (btop rounded boxes)
    0x25CF, 0x25CB,                          # ● ○
    0x2500, 0x2502, 0x250C, 0x2510, 0x2514, 0x2518,
    0x251C, 0x2524, 0x252C, 0x2534, 0x253C,  # ─│┌┐└┘├┤┬┴┼
    *range(0x2581, 0x2589),                  # ▁▂▃▄▅▆▇█
    0x2591,                                  # ░
]
BRAILLE = list(range(0x2800, 0x2900))

SETS = {
    # name: (bdf, codepoints)
    "regular": ("ter-u20n.bdf", ASCII + EXTRA + BRAILLE),
    "bold": ("ter-u20b.bdf", ASCII + [0x00B7, 0x2026]),  # titles + hero digits
}


def load_bdf(path):
    src = open(path, encoding="latin-1").read()
    glyphs = {}
    for m in re.finditer(r"ENCODING (\d+)\n.*?BBX (\d+) (\d+) (-?\d+) (-?\d+)\nBITMAP\n(.*?)ENDCHAR", src, re.S):
        cp, w, h = int(m.group(1)), int(m.group(2)), int(m.group(3))
        rows = [int(r, 16) for r in m.group(6).split()]
        if (w, h) != (10, 20) or len(rows) != 20:
            sys.exit(f"{path}: U+{cp:04X} is {w}x{h}, expected 10x20")
        glyphs[cp] = rows
    return glyphs


def main():
    out = [
        "#pragma once",
        "// Generated by tools/font/mkfont.py from Terminus 4.49.1 (ter-u20n/b.bdf).",
        "// Terminus Font is licensed under the SIL Open Font License 1.1:",
        "// third_party/terminus/OFL.TXT. Do not edit by hand.",
        "#include <stdint.h>",
        "",
        "#include \"platform.h\"  // FAST_DATA: keep glyphs in internal RAM",
        "",
        "namespace font_data {",
    ]
    for name, (bdf, cps) in SETS.items():
        glyphs = load_bdf(os.path.join(SRC, bdf))
        cps = sorted(set(cps))
        missing = [f"U+{c:04X}" for c in cps if c not in glyphs]
        if missing:
            sys.exit(f"{bdf}: missing {', '.join(missing)}")
        out.append(f"\nconstexpr uint16_t {name.upper()}_COUNT = {len(cps)};")
        out.append(f"FAST_DATA const uint16_t {name.upper()}_CODEPOINTS[{name.upper()}_COUNT] = {{")
        for i in range(0, len(cps), 12):
            out.append("    " + ", ".join(f"0x{c:04X}" for c in cps[i:i + 12]) + ",")
        out.append("};")
        out.append(f"FAST_DATA const uint16_t {name.upper()}_ROWS[{name.upper()}_COUNT][20] = {{")
        for c in cps:
            out.append("    {" + ", ".join(f"0x{r:04X}" for r in glyphs[c]) + f"}},  // U+{c:04X}")
        out.append("};")
    out.append("\n}  // namespace font_data")
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
