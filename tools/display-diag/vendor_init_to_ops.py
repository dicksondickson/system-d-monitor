"""Convert a vendor ST7701 init listing (SPI_WriteComm/SPI_WriteData/Delay
lines) into an Arduino_GFX batchOperation array.

usage: vendor_init_to_ops.py <listing.txt> <array_name>  > header.h
"""
import re, sys

src = open(sys.argv[1], "rb").read().decode("gb18030", "replace")
name = sys.argv[2]
ops = []                      # (kind, value)
for m in re.finditer(r"SPI_WriteComm\((0x[0-9A-Fa-f]+)\)|SPI_WriteData\((0x[0-9A-Fa-f]+)\)|Delay\((\d+)\)", src):
    if m.group(1): ops.append(("cmd", int(m.group(1), 16)))
    elif m.group(2): ops.append(("data", int(m.group(2), 16)))
    else: ops.append(("delay", int(m.group(3))))

out = ["BEGIN_WRITE,"]
i = 0
while i < len(ops):
    kind, v = ops[i]
    if kind == "cmd":
        data = []
        j = i + 1
        while j < len(ops) and ops[j][0] == "data":
            data.append(ops[j][1]); j += 1
        out.append(f"WRITE_COMMAND_8, 0x{v:02X},")
        for k in range(0, len(data), 255):
            chunk = data[k:k + 255]
            out.append(f"WRITE_BYTES, {len(chunk)}, " + ", ".join(f"0x{d:02X}" for d in chunk) + ",")
        i = j
    elif kind == "delay":
        assert v <= 255, "DELAY takes a uint8_t"
        out += ["END_WRITE,", f"DELAY, {v},", "BEGIN_WRITE,"]
        i += 1
    else:
        sys.exit(f"data byte 0x{v:02X} without a preceding command")
out.append("END_WRITE,")

print("#pragma once")
print("// Generated by tools/display-diag/vendor_init_to_ops.py from the vendor listing:")
print(f"//   {sys.argv[1].split('/')[-1]}")
print("#include <Arduino_GFX_Library.h>\n")
print(f"static const uint8_t {name}[] = {{")
for line in out: print("    " + line)
print("};")
